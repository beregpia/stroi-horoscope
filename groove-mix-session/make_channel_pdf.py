#!/usr/bin/env python3
"""Channel-Passport.pdf: каждый канал проекта — инсерты по порядку, посылы, что зачем."""
from fpdf import FPDF
import os

BASE = os.path.dirname(os.path.abspath(__file__))
DEJAVU = "/usr/share/fonts/truetype/dejavu/"

DARK = (32, 28, 24)
ACCENT = (224, 160, 80)
BLUE = (80, 160, 180)
RED = (192, 88, 64)
GREEN = (110, 150, 90)
GREY = (120, 112, 100)
TXT = (40, 36, 32)


class PDF(FPDF):
    def __init__(self):
        super().__init__("P", "mm", "A4")
        self.add_font("DejaVu", "", DEJAVU + "DejaVuSans.ttf")
        self.add_font("DejaVu", "B", DEJAVU + "DejaVuSans-Bold.ttf")
        self.set_auto_page_break(True, margin=16)
        self.set_margins(14, 14, 14)

    def header(self):
        if self.page_no() == 1:
            return
        self.set_font("DejaVu", "", 8)
        self.set_text_color(*GREY)
        self.cell(0, 6, "Паспорт каналов · инсерты · посылы · что зачем",
                  new_x="LMARGIN", new_y="NEXT", align="R")
        self.ln(1)

    def footer(self):
        self.set_y(-13)
        self.set_font("DejaVu", "", 8)
        self.set_text_color(*GREY)
        self.cell(0, 6, f"— {self.page_no()} —", align="C")

    def part(self, t):
        if self.get_y() > 230:
            self.add_page()
        self.ln(3)
        self.set_fill_color(*DARK)
        y = self.get_y()
        self.rect(14, y, 182, 10, style="F")
        self.set_xy(18, y + 1.6)
        self.set_font("DejaVu", "B", 12)
        self.set_text_color(*ACCENT)
        self.cell(0, 7, t, new_x="LMARGIN", new_y="NEXT")
        self.set_y(y + 12.5)

    def chan(self, name, route, pan, fader):
        # не отрывать шапку канала от содержимого
        if self.get_y() > 236:
            self.add_page()
        self.ln(2)
        self.set_font("DejaVu", "B", 11.5)
        self.set_text_color(*TXT)
        self.cell(0, 6.5, name, new_x="LMARGIN", new_y="NEXT")
        self.set_font("DejaVu", "B", 9)
        self.set_text_color(*BLUE)
        self.cell(0, 5, f"РОУТИНГ: {route}", new_x="LMARGIN", new_y="NEXT")
        self.set_font("DejaVu", "", 8.8)
        self.set_text_color(*GREY)
        self.cell(0, 4.8, f"Пан: {pan}   ·   Фейдер (старт): {fader}",
                  new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(*ACCENT)
        self.set_line_width(0.4)
        self.line(14, self.get_y() + 0.8, 196, self.get_y() + 0.8)
        self.ln(2.2)

    def ins(self, n, plug, sett, why):
        if self.get_y() > 262:
            self.add_page()
        self.set_x(17)
        self.set_font("DejaVu", "B", 9.1)
        self.set_text_color(*TXT)
        self.multi_cell(176, 4.9, f"{n}. {plug} — {sett}", new_x="LMARGIN", new_y="NEXT")
        self.set_x(22)
        self.set_font("DejaVu", "", 8.6)
        self.set_text_color(*GREY)
        self.multi_cell(170, 4.5, f"зачем: {why}", new_x="LMARGIN", new_y="NEXT")
        self.ln(0.8)

    def snd(self, text):
        if self.get_y() > 264:
            self.add_page()
        self.set_x(17)
        self.set_font("DejaVu", "", 8.9)
        self.set_text_color(*GREEN)
        self.multi_cell(176, 4.8, "→ " + text, new_x="LMARGIN", new_y="NEXT")

    def lab(self, t, color=RED):
        if self.get_y() > 260:
            self.add_page()
        self.set_x(16)
        self.set_font("DejaVu", "B", 8.8)
        self.set_text_color(*color)
        self.cell(0, 5, t, new_x="LMARGIN", new_y="NEXT")

    def note(self, text):
        self.set_x(17)
        self.set_font("DejaVu", "", 8.5)
        self.set_text_color(*GREY)
        self.multi_cell(174, 4.5, text, new_x="LMARGIN", new_y="NEXT")
        self.ln(0.8)

    def goldbox(self, title, rows, hbox):
        if self.get_y() + hbox > 272:
            self.add_page()
        y = self.get_y() + 2
        self.set_fill_color(252, 243, 228)
        self.set_draw_color(*ACCENT)
        self.set_line_width(0.5)
        self.rect(16, y, 178, hbox, style="DF")
        self.set_xy(22, y + 4)
        self.set_font("DejaVu", "B", 11)
        self.set_text_color(*RED)
        self.cell(0, 6, title, new_x="LMARGIN", new_y="NEXT")
        self.set_font("DejaVu", "", 9.2)
        self.set_text_color(*TXT)
        for r in rows:
            self.set_x(22)
            self.multi_cell(166, 5.4, "• " + r, new_x="LMARGIN", new_y="NEXT")
        self.set_y(y + hbox + 2)


